/** Render the original PDFs once for a lightweight, on-demand web reader.
 * Requires Poppler (pdfinfo / pdftoppm) and Sharp. Originals are never changed.
 * Run with an optional issue id to rebuild one publication.
 */
const fs = require('node:fs/promises');
const path = require('node:path');
const { execFile } = require('node:child_process');
const { promisify } = require('node:util');
const { createHash } = require('node:crypto');
const sharp = require('sharp');
const exec = promisify(execFile);
const root = path.resolve(__dirname, '..');
const sizes = [240, 960, 1920];
const quality = 84;
const recipe = `poppler-cropbox-srgb-webp-v1-${sizes}-${quality}`;

async function build() {
    const catalog = JSON.parse(await fs.readFile(path.join(root, 'content/magazines.json'), 'utf8'));
    const requested = process.argv[2];
    if (requested && !catalog.some(book => book.id === requested)) throw new Error(`Unknown issue: ${requested}`);
    for (const book of catalog.filter(book => !requested || book.id === requested)) {
        const pdf = path.join(root, book.pdf);
        const version = createHash('sha256').update(await fs.readFile(pdf)).update(recipe).digest('hex').slice(0, 12);
        const destination = path.join(root, 'images/magazines', book.id);
        await fs.mkdir(destination, { recursive: true });
        const manifestFile = path.join(destination, 'manifest.json');
        const existing = await fs.readFile(manifestFile, 'utf8').then(JSON.parse).catch(() => null);
        const info = (await exec('pdfinfo', [pdf])).stdout;
        const count = Number(info.match(/^Pages:\s+(\d+)/m)[1]);
        if (existing?.version === version && existing.pages.length === count) {
            const files = await fs.readdir(destination);
            if (files.filter(name => name.endsWith('.webp')).length === count * sizes.length) {
                console.log(`${book.id}: ${count} pages already current.`);
                continue;
            }
        }
        const pages = new Array(count);
        let next = 0;
        async function worker() {
            while (next < count) {
                const index = next++;
                const number = String(index + 1);
                const { stdout } = await exec('pdftoppm', ['-f', number, '-l', number, '-singlefile', '-cropbox', '-scale-to-x', '1920', '-scale-to-y', '-1', '-png', pdf], { encoding: 'buffer', maxBuffer: 64 * 1024 * 1024 });
                const metadata = await sharp(stdout).metadata();
                pages[index] = { width: metadata.width, height: metadata.height };
                const stem = `page-${number.padStart(3, '0')}`;
                for (const width of sizes) {
                    await sharp(stdout).resize({ width }).toColourspace('srgb').webp({ quality, effort: 4 }).toFile(path.join(destination, `${stem}-${width}.webp`));
                }
                if ((index + 1) % 16 === 0 || index + 1 === count) console.log(`${book.id}: ${index + 1}/${count}`);
            }
        }
        await Promise.all([worker(), worker()]);
        await fs.writeFile(manifestFile, JSON.stringify({ ...book, version, sizes, pages }) + '\n');
    }
    // Individual jobs can prepare independent issues concurrently. Publish the
    // shared library only after the complete archive has been built.
    if (requested) return;
    const library = [];
    for (const book of catalog) {
        const manifest = JSON.parse(await fs.readFile(path.join(root, 'images/magazines', book.id, 'manifest.json'), 'utf8').catch(() => 'null'));
        if (manifest) library.push({ ...book, pages: manifest.pages.length, manifest: `images/magazines/${book.id}/manifest.json?v=${manifest.version}` });
    }
    await fs.writeFile(path.join(root, 'js/magazine-library.js'), `// Generated by scripts/build-magazine-images.cjs.\nwindow.magazineLibrary = ${JSON.stringify(library, null, 2)};\n`);
    console.log(`Prepared ${library.length} publications.`);
}
build().catch(error => { console.error(error); process.exitCode = 1; });
