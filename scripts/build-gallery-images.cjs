// Regenerate gallery derivatives after changing a photo or gallery selection.
const fs = require('node:fs/promises');
const path = require('node:path');
const vm = require('node:vm');
const { createHash } = require('node:crypto');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');

async function main() {
    const sources = new Set();
    for (const file of ['portfolio.js', 'landscapes.js', 'extra_images.js']) {
        const code = await fs.readFile(path.join(root, 'js', file), 'utf8');
        const data = code.match(/const portfolioImages\s*=\s*(\[[\s\S]*?\n\]);/);
        if (!data) throw new Error(`Cannot read selection: ${file}`);
        for (const image of vm.runInNewContext(data[1])) sources.add(image.src);
    }
    await fs.mkdir(path.join(root, 'images/gallery'), { recursive: true });
    const entries = [];
    let originalBytes = 0, thumbnailBytes = 0;
    // Limit concurrency so a regeneration does not exhaust memory.
    const queue = [...sources];
    await Promise.all(Array.from({ length: 3 }, async () => {
        while (queue.length) {
            const src = queue.shift();
            const input = path.join(root, src);
            const metadata = await sharp(input).metadata();
            const rotated = [5, 6, 7, 8].includes(metadata.orientation);
            const width = rotated ? metadata.height : metadata.width;
            const height = rotated ? metadata.width : metadata.height;
            const id = createHash('sha256').update(src).digest('hex').slice(0, 16);
            const variants = [];
            originalBytes += (await fs.stat(input)).size;
            for (const size of [...new Set([480, 960, 1440].map(value => Math.min(value, width)))]) {
                const output = `images/gallery/${id}-${size}.webp`;
                const result = await sharp(input).rotate().resize({ width: size, withoutEnlargement: true })
                    .toColourspace('srgb').webp({ quality: 86, effort: 4 }).toFile(path.join(root, output));
                variants.push({ src: output, width: result.width });
                if (size === Math.min(960, width)) thumbnailBytes += result.size;
            }
            entries.push([src, { width, height, variants }]);
        }
    }));
    entries.sort(([a], [b]) => a.localeCompare(b));
    await fs.writeFile(path.join(root, 'js/gallery-images.js'),
        '// Generated by scripts/build-gallery-images.cjs. Originals remain unchanged.\n' +
        'window.galleryImageVariants = ' + JSON.stringify(Object.fromEntries(entries)) + ';\n');
    // Keep the complete composition for the shared link photograph.
    await sharp(path.join(root, 'images/landscapes/all/R1-08246-023A.jpg'))
        .rotate().resize({ width: 1200, withoutEnlargement: true }).toColourspace('srgb')
        .jpeg({ quality: 88, mozjpeg: true }).toFile(path.join(root, 'images/share.jpg'));
    console.log(JSON.stringify({ photos: entries.length, originalBytes, thumbnailBytes,
        reduction: `${(100 * (1 - thumbnailBytes / originalBytes)).toFixed(1)}%` }));
}
main().catch(error => { console.error(error); process.exitCode = 1; });
