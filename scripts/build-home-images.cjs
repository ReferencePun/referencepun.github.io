/** Small, full-composition derivatives for the homepage and Vogue gallery. */
const fs = require('node:fs/promises');
const path = require('node:path');
const sharp = require('sharp');
const root = path.resolve(__dirname, '..');

async function build() {
    const originals = 'images/home/originals';
    const files = (await fs.readdir(path.join(root, originals))).filter(file => /\.jpg$/i.test(file));
    const sources = files.map(file => [file.replace(/\.jpg$/i, ''), `${originals}/${file}`]);
    sources.push(
        ['transition', 'images/thumbnails/01 Issue 01 Transition.jpg'],
        ['transparency', 'images/thumbnails/02 Issue 02 Transparency.jpg'],
        ['transform', 'images/thumbnails/04 Issue 03 Transform.jpg'],
        ['lindsey-wixson', 'images/thumbnails/07 Presents Lindsey Wixson.jpg'],
        ['photojournalism', 'images/thumbnails/03 FNT Photojournalism.jpg'],
        ['madewell', 'images/thumbnails/whereiwanttobe2.jpg'],
        ['love-and-loss', 'images/thumbnails/FH000016lnew.jpg'],
        ['hitchhiking', 'images/thumbnails/FH000034.jpg']
    );
    const manifest = {};
    for (const [name, source] of sources) {
        const input = path.join(root, source);
        const info = await sharp(input).rotate().metadata();
        const rotated = [5, 6, 7, 8].includes(info.orientation);
        const width = rotated ? info.height : info.width;
        const height = rotated ? info.width : info.height;
        const variants = [];
        for (const size of [...new Set([480, 960, 1440].map(size => Math.min(size, width)))]) {
            const destination = `images/home/${name}-${size}.webp`;
            await sharp(input).rotate().resize({ width: size, withoutEnlargement: true }).toColourspace('srgb').webp({ quality: 86 }).toFile(path.join(root, destination));
            variants.push({ src: destination, width: size });
        }
        manifest[source] = { width, height, variants };
    }
    await fs.writeFile(path.join(root, 'js/home-images.js'), `// Generated by scripts/build-home-images.cjs.\nObject.assign(window.galleryImageVariants ||= {}, ${JSON.stringify(manifest, null, 2)});\n`);
    console.log(`Prepared ${sources.length} homepage images.`);
}
build().catch(error => { console.error(error); process.exitCode = 1; });
