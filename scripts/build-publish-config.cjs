/* Keep source photographs stored in Git without publishing unused originals.
 * The reader uses generated magazine pages; PDFs remain offline source files.
 * Regenerate after changing photo selections: npm run site:config
 */
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const assert = require('node:assert/strict');
const files = execFileSync('git', ['ls-files', '-z'], { encoding: 'utf8' }).split('\0').filter(Boolean);
const fileSet = new Set(files);
const read = file => fs.readFileSync(file, 'utf8');
const html = files.filter(file => file.endsWith('.html'));
const scripts = new Set();
for (const file of html) {
    for (const match of read(file).matchAll(/<script\b[^>]*\bsrc=["']([^"']+)["']/gi)) {
        const src = match[1].split('?')[0];
        if (/^(https?:)?\/\//.test(src)) continue;
        const local = path.posix.normalize(src.startsWith('/') ? src.slice(1) : path.posix.join(path.posix.dirname(file), src));
        if (fileSet.has(local)) scripts.add(local);
    }
}
// Both collections are selectable at runtime on the Film Photography page.
['js/portfolio.js', 'js/landscapes.js'].forEach(file => scripts.add(file));
const textFiles = [...html, ...scripts, ...files.filter(file => file.endsWith('.css'))];
const corpus = textFiles.filter(file => file !== 'js/gallery-images.js').map(read).join('\n');
const sourceRoots = ['images/commissioned', 'images/personal', 'images/landscapes', 'images/portfolio'];
const sources = files.filter(file => sourceRoots.some(root => file.startsWith(root + '/')));
const unused = new Set(sources.filter(file => !corpus.includes(file)));
const used = sources.filter(file => !unused.has(file));
assert(used.length > 250, 'Unexpectedly few photo references; inspect the site before changing publication rules.');

// Collapse fully unused directories; retain exact filenames in mixed folders.
function excludedWithin(directory) {
    const descendants = sources.filter(file => file.startsWith(directory + '/'));
    if (descendants.every(file => unused.has(file))) return [directory];
    const entries = [...new Set(descendants.map(file => file.slice(directory.length + 1).split('/')[0]))];
    return entries.flatMap(name => {
        const entry = directory + '/' + name;
        return fileSet.has(entry) ? (unused.has(entry) ? [entry] : []) : excludedWithin(entry);
    });
}
const exclusions = ['node_modules', '.qa', 'docs', 'tests', 'scripts', 'DEVELOPMENT.md', 'package.json', 'pdfs', ...sourceRoots.flatMap(excludedWithin)].sort();
const included = used.filter(file => path.posix.basename(file).startsWith('_')).sort();
const configuration = '# Generated by scripts/build-publish-config.cjs. Source assets remain stored in Git.\n'
    + '# PDF downloads are disabled; every image-based magazine page is still published.\n'
    + 'exclude:\n' + exclusions.map(file => '  - ' + JSON.stringify(file)).join('\n') + '\n'
    + 'include:\n' + included.map(file => '  - ' + JSON.stringify(file)).join('\n') + '\n';
const excluded = file => exclusions.some(entry => file === entry || file.startsWith(entry + '/'));
const published = files.filter(file => !excluded(file));
const bytes = published.reduce((total, file) => total + fs.statSync(file).size, 0);
assert(bytes < 1_000_000_000, 'Site exceeds the GitHub Pages 1 GB limit.');
for (const file of used) assert(!excluded(file), 'Selected photograph was excluded: ' + file);
for (const file of files.filter(file => file.startsWith('images/magazines/'))) assert(!excluded(file));

if (process.argv.includes('--check')) {
    assert.equal(read('_config.yml'), configuration, 'Run npm run site:config after changing photo selections.');
} else {
    fs.writeFileSync('_config.yml', configuration);
}
const stageIndex = process.argv.indexOf('--stage');
if (stageIndex !== -1) {
    const destination = path.resolve(process.argv[stageIndex + 1]);
    assert(!fs.existsSync(destination), 'Choose a new staging directory.');
    for (const file of published) {
        const target = path.join(destination, file);
        fs.mkdirSync(path.dirname(target), { recursive: true });
        fs.linkSync(path.resolve(file), target);
    }
}
console.log(`Publication: ${(bytes / 1e6).toFixed(1)} MB; ${used.length} selected source photographs and all magazine pages retained. ${unused.size} unused originals remain in Git.`);
